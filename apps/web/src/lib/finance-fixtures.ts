export function findVendorById(id: string): Vendor | null {
  return vendors.find((v) => v.id === id) ?? null
}

export function listExpenses(filters?: {
  building_id?: string
  from?: string
  to?: string
  category?: ExpenseCategory
}): Expense[] {
  return expenses.filter((e) => {
    if (filters?.building_id && e.building_id !== filters.building_id) return false
    if (filters?.from && e.expense_date < filters.from) return false
    if (filters?.to && e.expense_date > filters.to) return false
    if (filters?.category && e.category !== filters.category) return false
    return true
  })
}

export function totalExpenses(filters?: {
  building_id?: string
  from?: string
  to?: string
  category?: ExpenseCategory
}): number {
  return listExpenses(filters).reduce((sum, e) => sum + e.amount_cents, 0)
}

export function expensesByCategory(filters?: {
  building_id?: string
  from?: string
  to?: string
}): Record<ExpenseCategory, number> {
  const result = {} as Record<ExpenseCategory, number>
  const cats: ExpenseCategory[] = [
    'advertising', 'cleaning_maintenance', 'insurance', 'mortgage_interest',
    'repairs', 'supplies', 'taxes', 'utilities', 'management_fees',
    'professional_fees', 'other',
  ]
  for (const cat of cats) {
    result[cat] = totalExpenses({ ...filters, category: cat })
  }
  return result
}

export function vendorYtdTotal(vendorId: string, year: number): number {
  const from = `${year}-01-01`
  const to = `${year}-12-31`
  return expenses
    .filter((e) => e.vendor_id === vendorId && e.expense_date >= from && e.expense_date <= to)
    .reduce((sum, e) => sum + e.amount_cents, 0)
}

export function vendor1099Candidates(
  year: number,
): { vendor: Vendor; total_cents: number }[] {
  const THRESHOLD = 60000 // $600.00 in cents
  return vendors
    .filter((v) => !v.is_corporation)
    .map((v) => ({ vendor: v, total_cents: vendorYtdTotal(v.id, year) }))
    .filter((item) => item.total_cents > THRESHOLD)
    .sort((a, b) => b.total_cents - a.total_cents)
}
